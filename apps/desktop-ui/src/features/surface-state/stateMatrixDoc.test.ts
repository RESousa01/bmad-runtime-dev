import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

import { hostErrorPresentation, type LocalErrorCode } from "./surfaceState";

/**
 * Keeps `docs/design/state-matrix.md` equal to the mapping it documents.
 *
 * Phase 5, D1. The acceptance criterion is that every `LocalErrorCode` is
 * mapped or explicitly listed as falling to the generic fallback. A hand-written
 * table satisfies that on the day it is written and stops the first time someone
 * adds a code, silently, because prose cannot fail a build.
 *
 * This lives in the test suite rather than in `tools/` on purpose, and the first
 * attempt is why. A bare-node gate cannot import TypeScript, so it read the
 * mapping by regex -- and produced a table that looked authoritative while
 * being wrong in the worst way available: it found 27 of the 30 codes and
 * attributed three `because` sentences to the wrong rows, so `unauthorized`
 * carried `not_found`'s explanation. A document that is confidently wrong is
 * worse than one that is merely stale.
 *
 * Importing the real module cannot misread it. The compiler already makes the
 * mapping total, because it is a `Record<LocalErrorCode, …>`; this makes the
 * prose match the mapping.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const docPath = path.resolve(here, "../../../../../docs/design/state-matrix.md");

const BEGIN = "<!-- BEGIN GENERATED: host-error-states -->";
const END = "<!-- END GENERATED: host-error-states -->";

function renderTable(): string {
  const codes = (Object.keys(hostErrorPresentation) as LocalErrorCode[]).sort();
  const rows = codes.map((code) => {
    const { generic, recovery, state } = hostErrorPresentation[code];
    const note = generic === true
      ? "generic fallback"
      : recovery.kind === "none" ? recovery.because : "";
    return `| \`${code}\` | ${state} | ${recovery.kind} | ${note} |`;
  });
  const generic = codes.filter((code) => hostErrorPresentation[code].generic === true);
  return [
    BEGIN,
    "",
    "<!-- Generated by features/surface-state/stateMatrixDoc.test.ts.",
    "     Do not edit between the markers; run the suite with UPDATE_STATE_MATRIX=1. -->",
    "",
    `${codes.length} host error codes, all mapped.`,
    "",
    "| Code | State | Recovery | Note |",
    "|---|---|---|---|",
    ...rows,
    "",
    generic.length === 0
      ? "No code falls to the generic fallback."
      : `Falling to the generic fallback, deliberately: ${generic.map((code) => `\`${code}\``).join(", ")}.`,
    "",
    END,
  ].join("\n");
}

describe("the state matrix document", () => {
  it("lists every host error code exactly as the mapping does", () => {
    const doc = readFileSync(docPath, "utf8");
    const begin = doc.indexOf(BEGIN);
    const end = doc.indexOf(END);
    expect(begin, "state-matrix.md is missing the generated-section markers").toBeGreaterThan(-1);
    expect(end).toBeGreaterThan(begin);

    const table = renderTable();
    const updated = doc.slice(0, begin) + table + doc.slice(end + END.length);

    // Writing only on request, and only here. A test that writes as a side
    // effect of a normal run is one that can turn a red suite green by
    // rewriting the thing it was checking.
    if (process.env.UPDATE_STATE_MATRIX === "1") {
      writeFileSync(docPath, updated);
    }

    expect(
      doc.slice(begin, end + END.length),
      "docs/design/state-matrix.md is out of date. Re-run with UPDATE_STATE_MATRIX=1.",
    ).toBe(table);
  });

  it("documents a recovery for every code, and a reason wherever there is none", () => {
    // The two halves of the criterion, asserted against the mapping rather than
    // against the prose, so a doc rewrite cannot satisfy them on its own.
    for (const code of Object.keys(hostErrorPresentation) as LocalErrorCode[]) {
      const { recovery, state } = hostErrorPresentation[code];
      expect(state, code).toBeTruthy();
      if (recovery.kind === "none") expect(recovery.because.length, code).toBeGreaterThan(0);
    }
  });
});
