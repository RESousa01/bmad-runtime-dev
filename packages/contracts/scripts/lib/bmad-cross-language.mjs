import path from "node:path";
import { canonicalHash, canonicalize } from "./canonical-json.mjs";
import { parseStrictJson } from "./strict-json.mjs";

export const BMAD_CROSS_LANGUAGE_SCHEMAS = Object.freeze([
  ["bmad-source-identity", "BmadSourceIdentity", "BmadSourceIdentity"],
  ["bmad-source-accounting", "BmadSourceAccounting", "BmadSourceAccounting"],
  ["bmad-capability-catalog", "BmadCapabilityCatalog", "BmadCapabilityCatalog"],
  ["bmad-skill-package", "BmadSkillPackage", "BmadSkillPackage"],
  ["bmad-session", "BmadSession", "BmadSession"],
  ["bmad-artifact", "BmadArtifact", "BmadArtifact"],
  ["bmad-builder-authoring", "BuilderAuthoringObject", "BuilderAuthoringObject"],
  ["bmad-builder-promotion", "BmadBuilderPromotion", "BmadBuilderPromotion"],
  ["bmad-eval", "BmadEval", "BmadEval"],
  ["bmad-module", "BmadModule", "BmadModule"],
  ["bmad-script-plan", "BmadScriptPlan", "BmadScriptPlan"],
  ["bmad-config", "BmadConfig", "BmadConfig"],
  ["bmad-customization", "BmadCustomization", "BmadCustomization"],
  ["bmad-memory", "BmadMemory", "BmadMemory"],
  ["bmad-upgrade", "BmadUpgrade", "BmadUpgrade"],
]);

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function pascal(value) {
  return value.split("-").map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join("");
}

function fixtureName(value) {
  return value
    .replace(/^sapphirus\.bmad-/u, "")
    .replace(/\.v[0-9]+$/u, "")
    .replaceAll("_", "-")
    .replaceAll(".", "-");
}

function fixtureEnvelope(schemaId, branch, document) {
  const canonicalJson = canonicalize(document);
  return {
    schemaVersion: "sapphirus.bmad-cross-language-fixture.v1",
    schemaId,
    branch,
    document,
    canonicalJson,
    expectedHash: canonicalHash({
      purpose: "bmad-cross-language-fixture",
      schemaMajor: "v1",
      value: document,
    }).serializedHash,
  };
}

function prefixTypescriptDeclarations(source, prefix) {
  const names = [...source.matchAll(/^export (?:type|interface) ([A-Za-z][A-Za-z0-9_]*)/gmu)]
    .map((match) => match[1])
    .sort((left, right) => right.length - left.length);
  let output = source;
  for (const name of names) {
    output = output.replace(new RegExp(`\\b${name}\\b`, "gu"), `${prefix}${name}`);
  }
  return output;
}

function csharpCatalog(schemas) {
  const rows = schemas.map(({ protocolVersion, csharpType }) =>
    `        new(${JSON.stringify(protocolVersion)}, typeof(${csharpType})),`).join("\n");
  return `// <auto-generated by scripts/generate-bmad.mjs; DO NOT EDIT.>
namespace Sapphirus.Contracts.Generated;

/// <summary>Closed, versioned roots in the canonical BMAD contract family.</summary>
public static class BmadContracts
{
    public readonly record struct Contract(string ProtocolVersion, global::System.Type WireType);

    public static global::System.Collections.Generic.IReadOnlyList<Contract> All { get; } =
    [
${rows}
    ];
}
`;
}

export async function buildBmadCrossLanguageOutputs({
  packageRoot,
  schemas,
  expectedFiles,
  generateTypescript,
  rustSource,
}) {
  const outputs = new Map();
  const schemaByName = new Map(schemas.map((schema) => [
    schema.$id.slice(schema.$id.lastIndexOf("/") + 1, -".schema.json".length),
    schema,
  ]));
  const descriptors = BMAD_CROSS_LANGUAGE_SCHEMAS.map(([name, rustType, csharpType]) => {
    const schema = schemaByName.get(name);
    if (!schema) throw new Error(`SRC-08 schema is unavailable: ${name}`);
    return {
      name,
      schemaId: schema.$id,
      protocolVersion: schema.title,
      rustType,
      csharpType,
    };
  });

  const typescriptParts = [];
  for (const descriptor of descriptors) {
    let schema = structuredClone(schemaByName.get(descriptor.name));
    delete schema.$id;
    const generated = await generateTypescript(schema, descriptor.name, {
      bannerComment: "",
      cwd: path.join(packageRoot, "schemas"),
      format: true,
      ignoreMinAndMaxItems: true,
      unreachableDefinitions: false,
    });
    typescriptParts.push(prefixTypescriptDeclarations(generated, pascal(descriptor.name)));
  }
  outputs.set(
    "generated/typescript/bmad.ts",
    `// @generated by scripts/generate-bmad.mjs; DO NOT EDIT.\n\n${typescriptParts.join("\n")}`,
  );
  if (rustSource !== null) {
    outputs.set(
      "generated/rust/bmad.rs",
      `// @generated by scripts/generate-bmad.mjs; DO NOT EDIT.\n// This is the qualified cargo-typify production tree, materialized as the BMAD wire surface.\n${rustSource}`,
    );
    outputs.set("generated/csharp/BmadContracts.cs", csharpCatalog(descriptors));
  }

  const family = parseStrictJson(await readFile(
    path.join(packageRoot, "tests", "fixtures", "bmad", "contract-family-v1.json"),
    "utf8",
  ));
  const migration = parseStrictJson(await readFile(
    path.join(packageRoot, "tests", "fixtures", "bmad", "builder-draft-v1-to-v2.json"),
    "utf8",
  ));
  const documents = family.documents.map(({ schema, value }) => ({
    name: fixtureName(value.schemaVersion),
    schemaId: schemaByName.get(schema.slice(0, -".schema.json".length)).$id,
    branch: value.schemaVersion,
    document: value,
  }));
  documents.push({
    name: "capability-catalog",
    schemaId: schemaByName.get("bmad-capability-catalog").$id,
    branch: "catalog",
    document: parseStrictJson(expectedFiles.get("fixtures/valid/bmad/capability-catalog.json")),
  });
  documents.push({
    name: "builder-authoring-v2",
    schemaId: schemaByName.get("bmad-builder-authoring").$id,
    branch: "authoring-v2",
    document: migration.expected,
  });
  documents.push({
    name: "upgrade",
    schemaId: schemaByName.get("bmad-upgrade").$id,
    branch: "deterministic-with-defaults",
    document: migration.manifest,
  });

  for (const name of [
    "builder-agent-draft",
    "builder-workflow-draft",
    "builder-agent-revision",
    "builder-workflow-revision",
    "builder-agent-analysis-deterministic",
    "builder-workflow-analysis-deterministic",
    "builder-agent-analysis-model-lens",
    "builder-workflow-analysis-model-lens",
  ]) {
    const relativePath = `fixtures/valid/bmad/${name}.json`;
    documents.push({
      name,
      schemaId: schemaByName.get("bmad-builder-authoring").$id,
      branch: name,
      document: parseStrictJson(expectedFiles.get(relativePath)),
    });
  }

  const promotion = documents.find(({ name }) => name === "builder-promotion");
  const transitions = [
    ["draft", "validated"],
    ["validated", "analysed"],
    ["analysed", "evaluated"],
    ["evaluated", "reviewed"],
    ["reviewed", "approved"],
    ["approved", "staged"],
    ["staged", "installed"],
    ["installed", "active"],
    ["active", "superseded"],
    ["active", "rolled_back"],
    ["superseded", "rolled_back"],
    ["installed", "uninstalled"],
    ["active", "uninstalled"],
    ["superseded", "uninstalled"],
    ["rolled_back", "uninstalled"],
  ];
  for (const [fromState, toState] of transitions) {
    documents.push({
      name: `promotion-${fromState}-to-${toState}`,
      schemaId: promotion.schemaId,
      branch: `${fromState}->${toState}`,
      document: { ...structuredClone(promotion.document), fromState, toState },
    });
  }

  const validPaths = [];
  for (const fixture of documents) {
    const relativePath = `fixtures/bmad/valid/${fixture.name}.json`;
    outputs.set(relativePath, stableJson(fixtureEnvelope(
      fixture.schemaId,
      fixture.branch,
      fixture.document,
    )));
    validPaths.push(relativePath);
  }

  const rejectionPaths = [];
  const rootFixture = new Map();
  for (const fixture of documents) {
    if (!rootFixture.has(fixture.schemaId)) rootFixture.set(fixture.schemaId, fixture);
  }
  for (const descriptor of descriptors) {
    const fixture = rootFixture.get(descriptor.schemaId);
    const relativePath = `fixtures/bmad/rejected/${descriptor.name}-unknown-property.json`;
    outputs.set(relativePath, stableJson({
      schemaVersion: "sapphirus.bmad-cross-language-rejection.v1",
      id: `${descriptor.name}-unknown-property`,
      schemaId: descriptor.schemaId,
      reason: "unknown_property",
      document: { ...structuredClone(fixture.document), futureAuthority: true },
    }));
    rejectionPaths.push(relativePath);
  }

  const allowed = new Set(transitions.map(([from, to]) => `${from}->${to}`));
  const lifecycle = [
    "draft", "validated", "analysed", "evaluated", "reviewed", "approved",
    "staged", "installed", "active", "superseded", "rolled_back", "uninstalled",
  ];
  for (const fromState of lifecycle) {
    for (const toState of lifecycle) {
      if (allowed.has(`${fromState}->${toState}`)) continue;
      const relativePath =
        `fixtures/bmad/rejected/promotion-${fromState}-to-${toState}.json`;
      outputs.set(relativePath, stableJson({
        schemaVersion: "sapphirus.bmad-cross-language-rejection.v1",
        id: `promotion-${fromState}-to-${toState}`,
        schemaId: promotion.schemaId,
        reason: "forbidden_transition",
        document: { ...structuredClone(promotion.document), fromState, toState },
      }));
      rejectionPaths.push(relativePath);
    }
  }

  outputs.set("fixtures/bmad/catalog.json", stableJson({
    schemaVersion: "sapphirus.bmad-cross-language-fixtures.v1",
    schemas: descriptors,
    roundTripOrder: ["typescript", "rust", "csharp", "rust", "typescript"],
    validFixtures: validPaths.sort(),
    rejectionFixtures: rejectionPaths.sort(),
  }));
  return outputs;
}
